def catalog():
    """返回稳定目录：按类别分组，每行是 id、名字、适用场景，供 system 前缀使用。"""
    groups = {}
    for key, item in LENSES.items():
        groups.setdefault(item["category"], []).append(
            f"  - {key} {item['name']}：{item['when']}")
    lines = []
    for category, items in groups.items():
        lines.append(f"[{category}]")
        lines.extend(items)
    return "\n".join(lines)


def detail(key):
    """返回单个镜头的提问清单；未知 id 返回 None。"""
    item = LENSES.get((key or "").strip().lower())
    if item is None:
        return None
    lines = [f"{item['name']} · 提问清单："]
    lines += [f"  {i}. {q}" for i, q in enumerate(item["questions"], 1)]
    return "\n".join(lines)
